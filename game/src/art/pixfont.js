export const textWidth = (s, sc = 1) => String(s).length * 4 * sc - sc;
// Draw text into a Graphics object at (x, y), top-left aligned. Returns the right edge.
export function pixText(g, s, x, y, color, sc = 1, alpha = 1) {
  g.fillStyle(color, alpha);
  let cx = Math.round(x);
  for (const ch of String(s)) {
    const glyph = F[ch] || F[ch.toUpperCase()] || F[' '];
    for (let j = 0; j < 5; j++) for (let i = 0; i < 3; i++) if (glyph[j][i] === '#') g.fillRect(cx + i * sc, Math.round(y) + j * sc, sc, sc);
    cx += 4 * sc;
  }
  return cx;
}
